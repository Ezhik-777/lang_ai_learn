import { LANGUAGES, type Language } from "@/lib/cefr";

export function listeningSentencePrompt(language: Language, level: string) {
  const lang = LANGUAGES[language].nameRu;
  const target = lang === "Немецкий" ? "немецком" : "английском";
  const langInstr =
    language === "de"
      ? "Все умлауты на месте (ä/ö/ü/ß). Существительные с заглавной. Без markdown."
      : "Корректная орфография. Без markdown.";
  return {
    system: `Сгенерируй фразу на ${target} для упражнения АУДИРОВАНИЕ — пользователь её услышит и попробует записать что услышал.

ТРЕБОВАНИЯ:
- Уровень CEFR: ${level}
- Длина: 6-14 слов.
- Бытовая, естественная разговорная фраза (диалог, объявление, фрагмент истории). НЕ философия.
- Подходит уровню: A1/A2 — простые; B1/B2 — обычная речь; C1/C2 — нюансы и устойчивые выражения.
- БЕЗ имён собственных, которые трудно записать (никаких "Schwarzwald", "Sebastian").
- Без чисел, дат — слишком легко записать на слух не на изучаемом языке.

${langInstr}

Верни строго JSON: {"target": string, "translation_ru": string}.`,
    user: `Уровень ${level}. Новая фраза для аудирования.`,
  };
}

export function listeningCheckPrompt(
  language: Language,
  target: string,
  userInput: string,
) {
  const lang = LANGUAGES[language].nameRu;
  return {
    system: `Студент изучает ${lang} язык. Он услышал фразу и записал то, что услышал.

ОЦЕНИ как насколько он понял на слух.

ПРАВИЛА ОЦЕНКИ:
- Регистр (заглавные/строчные) игнорируй полностью.
- Пунктуацию игнорируй (точки, запятые, восклицательные).
- Очевидные опечатки (одна-две буквы) считай близким, но не идеальным — снимай 2-3 балла.
- Пропуск или замена ключевого слова — серьёзнее, снимай 10-25 баллов.
- Перепутанная форма слова (Genitiv вместо Dativ, прошедшее вместо настоящего) — это аудирование, не грамматика, снимай мягко (5-10).
- Если записал на другом языке — score ≤ 30.

Шкала:
- 100 — идеальное совпадение (с точностью до регистра и пунктуации)
- 90-99 — мелкие опечатки
- 70-89 — почти всё правильно, 1-2 неверных слова
- 50-69 — половина смысла поймана
- <50 — основное не понял

Верни СТРОГО JSON:
{
  "score": 0-100,
  "wrong_words": [string],     // слова в записи студента, которых нет/неправильны
  "missed_words": [string],    // слова из target, которые студент пропустил
  "feedback_ru": string        // 1-2 предложения на русском: что хорошо/что улучшить
}`,
    user: `Target (что произнесли): «${target}»
Записал студент: «${userInput}»

Оцени.`,
  };
}
